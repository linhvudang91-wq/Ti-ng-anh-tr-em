export function getDailyMissionForDate(grade: GradeLevel, dateStr?: string, skill?: DailySkillType): DailyLearningMission {
  const targetDate = dateStr || new Date().toISOString().split('T')[0];
  
  // Find curated mission matching grade and skill
  let matched = CURATED_DAILY_MISSIONS.find(m => m.grade === grade && (!skill || m.skill === skill));
  if (!matched) {
    matched = CURATED_DAILY_MISSIONS.find(m => m.grade === grade) || CURATED_DAILY_MISSIONS[0];
  }

  return {
    ...matched,
    date: targetDate,
    dayOfYear: Math.floor((new Date().getTime() - new Date(new Date().getFullYear(), 0, 0).getTime()) / (1000 * 60 * 60 * 24)),
    skill: skill || matched.skill,
  };
}
