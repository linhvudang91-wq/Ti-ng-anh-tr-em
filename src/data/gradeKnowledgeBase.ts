/**
 * Lấy toàn bộ danh sách từ vựng theo khối lớp chỉ định (Lớp 3 - Lớp 9)
 */
export function getWordsByGrade(grade: GradeLevel): WordItem[] {
  return GRADE_KNOWLEDGE_BASE_WORDS.filter((w) => w.grade === grade);
}

/**
 * Lấy danh sách từ vựng của ngày hôm nay (Daily Workout) theo khối lớp và ngày
 * Hỗ trợ chọn số từ học mỗi ngày (mặc định 5 từ/ngày)
 */
export function getDailyWords(grade: GradeLevel, dayNumber: number = 1, count: number = 5): WordItem[] {
  const gradeWords = getWordsByGrade(grade);
  if (gradeWords.length === 0) return [];

  // Lọc theo dayBucket nếu có
  const bucketWords = gradeWords.filter((w) => w.dayBucket === dayNumber);
  if (bucketWords.length >= count) {
    return bucketWords.slice(0, count);
  }

  // Nếu trong ngày chưa đủ số lượng, lấy vòng lặp từ gradeWords
  const startIndex = ((dayNumber - 1) * count) % gradeWords.length;
  const result: WordItem[] = [];
  for (let i = 0; i < count; i++) {
    result.push(gradeWords[(startIndex + i) % gradeWords.length]);
  }
  return result;
}

/**
 * Thống kê từ vựng theo khối lớp: Tổng số từ, Số từ lõi SGK, Số từ mở rộng nâng cao
 */
export function getGradeVocabularyStats(grade: GradeLevel) {
  const words = getWordsByGrade(grade);
  const coreCount = words.filter((w) => w.isCore).length;
  const advancedCount = words.filter((w) => !w.isCore).length;
  const topics = Array.from(new Set(words.map((w) => w.topic || 'Tổng hợp')));

  return {
    total: words.length,
    coreCount,
    advancedCount,
    topics,
  };
}

/**
 * Tra cứu nhanh từ vựng trong kho kiến thức
 */
export function searchVocabulary(query: string, grade?: GradeLevel): WordItem[] {
  const cleanQ = query.trim().toLowerCase();
  if (!cleanQ) {
    return grade ? getWordsByGrade(grade) : GRADE_KNOWLEDGE_BASE_WORDS;
  }

  return GRADE_KNOWLEDGE_BASE_WORDS.filter((w) => {
    if (grade && w.grade !== grade) return false;
    return (
      w.word.toLowerCase().includes(cleanQ) ||
      w.meaningVi.toLowerCase().includes(cleanQ) ||
      (w.topic && w.topic.toLowerCase().includes(cleanQ)) ||
      (w.collocation && w.collocation.toLowerCase().includes(cleanQ))
    );
  });
}
